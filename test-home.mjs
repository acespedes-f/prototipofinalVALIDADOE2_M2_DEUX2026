import {readFile, access} from 'node:fs/promises';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const root=import.meta.dirname;
const [js,css]=await Promise.all(['app.js','styles.css'].map(x=>readFile(resolve(root,x),'utf8')));
assert.match(js,/<h1>Atlas <span>de los Oficios<\/span><\/h1>/);
assert.match(js,/const elquiNames=\[/);
assert.match(js,/const chiloeNames=\[/);
assert.match(js,/data-action="v51-enter"/);
assert.match(js,/state\.homeWork=\(!fromCase&&caseId==='petorca'\)\?id:null/);
