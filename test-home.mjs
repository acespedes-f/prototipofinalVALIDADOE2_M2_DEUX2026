assert.match(js,/data-action=\"v54-menu\"/);
assert.match(js,/data-action=\"v54-case\"/);
assert.match(js,/arrangeHome\(caseId,null\)/);
for(const c of ['elqui','chiloe'])for(let i=1;i<=5;i++)await access(resolve(root,'assets',`caso-${c}-${String(i).padStart(2,'0')}.webp`));
